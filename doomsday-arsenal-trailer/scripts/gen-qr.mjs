// Generates src/qr-data.js (a QR code for the CurseForge link) from src/config.js.
// Run automatically by the renderer; run by hand with `npm run qr` after changing the link.
import QRCode from 'qrcode';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CONFIG } from '../src/config.js';

export function generateQr(link = CONFIG.link) {
  const qr = QRCode.create(link, { errorCorrectionLevel: 'M' });
  const size = qr.modules.size;
  const bits = Array.from(qr.modules.data, (b) => (b ? '1' : '0')).join('');
  const out = `// Generated by scripts/gen-qr.mjs — do not edit by hand.\nexport const QR = { link: ${JSON.stringify(link)}, size: ${size}, bits: '${bits}' };\n`;
  writeFileSync(new URL('../src/qr-data.js', import.meta.url), out);
  return size;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(`QR code written (${generateQr()} modules).`);
}
